import type {
  ChangeStatus,
  DiffFile,
  Hunk,
  LineType,
  Project,
} from '../types'

type Row = [LineType, string]

function hunk(
  context: string,
  oldStart: number,
  newStart: number,
  rows: Row[],
): Hunk {
  let oldNo = oldStart
  let newNo = newStart

  const lines = rows.map(([type, content]) => {
    if (type === 'context') {
      return { type, content, oldNo: oldNo++, newNo: newNo++ }
    }
    if (type === 'add') {
      return { type, content, newNo: newNo++ }
    }
    return { type, content, oldNo: oldNo++ }
  })

  const oldCount = lines.filter((line) => line.type !== 'add').length
  const newCount = lines.filter((line) => line.type !== 'del').length
  const label = context ? ` ${context}` : ''

  return {
    header: `@@ -${oldStart},${oldCount} +${newStart},${newCount} @@${label}`,
    lines,
  }
}


