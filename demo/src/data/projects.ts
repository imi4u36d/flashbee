export function fileStats(file: DiffFile) {
  let additions = 0
  let deletions = 0
  let hunks = file.hunks.length

  for (const diffHunk of file.hunks) {
    for (const line of diffHunk.lines) {
      if (line.type === 'add') additions += 1
      if (line.type === 'del') deletions += 1
    }
  }

  return { additions, deletions, hunks }
}

export function projectStats(project: Project) {
  return project.files.reduce(
    (total, file) => {
      const stats = fileStats(file)
      total.additions += stats.additions
      total.deletions += stats.deletions
      return total
    },
    { additions: 0, deletions: 0 },
  )
}

export function pathParts(path: string) {
  const slash = path.lastIndexOf('/')
  if (slash === -1) return { name: path, dir: '' }
  return { name: path.slice(slash + 1), dir: path.slice(0, slash) }
}
